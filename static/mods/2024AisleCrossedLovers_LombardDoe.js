                    variable: Number(slide?.variable ?? 0),
                    operator: slide?.operator || ">",
                    amount: Number(slide?.amount ?? 0),
                    outcomeCondition: slide?.outcomeCondition || "ignore",
                    title: slide?.title || "",
                    subtitle: slide?.subtitle || "",
                    content: slide?.content || "",
                    image: slide?.image,
