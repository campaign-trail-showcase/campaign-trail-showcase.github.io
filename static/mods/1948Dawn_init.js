function addHistoricalRunningMateColumn() {
    const holder = document.getElementById("overall_details_container");
    if (!holder) {
        return;
    }

    const tables = holder.querySelectorAll("table");
    if (tables.length < 2) {
        return;
    }

    const historicalTable = tables[tables.length - 1];
    const rows = historicalTable.rows;
    if (rows.length != HistName.length + 1 || rows[0].cells.length != 4) {
        return;
    }

    for (let i = 1; i < rows.length; i++) {
        if (!rows[i].cells[0] || rows[i].cells.length != 4) {
            return;
        }
        const name = rows[i].cells[0].textContent.replace(/^[\s\-]+/, "").replace(/\s+/g, " ").trim();
        if (name != HistName[i - 1] || !Object.prototype.hasOwnProperty.call(vpTableHistorical, name)) {
            return;
        }
    }

    const heading = rows[0].cells[0].cloneNode(false);
    heading.textContent = "Running Mate";
    heading.removeAttribute("id");
    heading.id = "running-mate-historical";
    rows[0].insertBefore(heading, rows[0].cells[1]);

    for (let i = 1; i < rows.length; i++) {
        const name = HistName[i - 1];
        const cell = rows[i].insertCell(1);
        cell.textContent = vpTableHistorical[name];
    }
}

